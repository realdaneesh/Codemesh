const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { importWorkspaceFiles, MAX_BATCH_BYTES, MAX_BATCH_FILES } = require('../dist/services/batchImport');
const { MAX_FILE_BYTES } = require('../dist/types/fileTransfer');
async function main() {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'codemesh-batch-'));
  let groups = 0;
  const pass = text => { groups++; console.log('PASS: ' + text); };
  const files = names => names.map(path => ({ path, size: 4 }));
  const options = { isActive: () => true, isDirty: () => false, confirm: async () => true, review: async () => true,
    request: async () => 'text', isCancelled: () => false, progress() {} };
  const run = (names, overrides = {}) => importWorkspaceFiles(root, files(names), { ...options, ...overrides });
  let requests = 0;
  assert.deepEqual((await run(['no/create.txt'], { review: async (f, bytes) => {
    assert.equal(bytes, 4); assert.equal(f[0].path, 'no/create.txt'); assert.deepEqual(await fs.readdir(root), []); return false;
  }, request: async () => { requests++; return 'text'; } })).map(r => r.status), ['cancelled']);
  assert.equal(requests, 0); assert.deepEqual(await fs.readdir(root), []);
  pass('zero requests/directories/writes before confirmation; review decline reports every file');
  let pending = 0, maxPending = 0;
  const results = await run(['nested/a.txt', 'bad.txt', 'nested/b.txt'], { request: async name => {
    pending++; maxPending = Math.max(maxPending, pending); await new Promise(r => setTimeout(r, 5)); pending--;
    if (name === 'bad.txt') throw Error('owner changed'); return 'text';
  } });
  assert.deepEqual(results.map(r => r.status), ['imported', 'failed', 'imported']); assert.equal(maxPending, 1);
  assert.equal(await fs.readFile(path.join(root, 'nested/b.txt'), 'utf8'), 'text');
  pass('nested paths, sequential requests, mixed failure retains both successful files');
  await fs.writeFile(path.join(root, 'existing.txt'), 'original');
  assert.equal((await run(['existing.txt'], { confirm: async (_, exists) => { assert.ok(exists); return false; } }))[0].status, 'declined');
  assert.equal(await fs.readFile(path.join(root, 'existing.txt'), 'utf8'), 'original');
  assert.equal((await run(['existing.txt']))[0].status, 'imported');
  pass('existing file unchanged on decline, overwritten only on approval');
  assert.equal((await run(['existing.txt'], { isDirty: () => true }))[0].status, 'failed');
  let dirty = false;
  assert.equal((await run(['existing.txt'], { isDirty: () => dirty, confirm: async () => { dirty = true; return true; } }))[0].status, 'failed');
  assert.equal(await fs.readFile(path.join(root, 'existing.txt'), 'utf8'), 'text');
  pass('dirty editor before and during overwrite blocks write');
  let cancelled = false;
  assert.deepEqual((await run(['cancel-first.txt', 'cancel-next.txt'], { isCancelled: () => cancelled, progress: count => { if (count === 1) cancelled = true; } })).map(r => r.status), ['imported', 'cancelled']);
  cancelled = false;
  assert.equal((await run(['cancel-in-flight.txt'], { isCancelled: () => cancelled, request: async () => { cancelled = true; return 'text'; } }))[0].status, 'cancelled');
  await assert.rejects(fs.stat(path.join(root, 'cancel-in-flight.txt')));
  pass('cancellation after success and during request preserves completed import and blocks next write');
  let active = true;
  assert.deepEqual((await run(['refresh-first.txt', 'refresh-next.txt'], { isActive: () => active, progress: count => { if (count === 1) active = false; } })).map(r => r.status), ['imported', 'cancelled']);
  active = true;
  assert.equal((await run(['refresh-in-flight.txt'], { isActive: () => active, request: async () => { active = false; return 'text'; } }))[0].status, 'cancelled');
  pass('manifest refresh after success and during request invalidates remaining writes');
  for (const name of ['../escape', '/absolute', 'C:\\escape', 'a/../bad', 'nul.txt', '.git/config', '.env']) await assert.rejects(run([name]));
  await assert.rejects(run(['Case.txt', 'case.txt']));
  pass('malicious paths, excluded paths and case collisions rejected before review');
  let reviews = 0;
  const rejected = overrides => ({ ...options, review: async () => { reviews++; return true; }, ...overrides });
  await assert.rejects(importWorkspaceFiles(root, Array.from({length: MAX_BATCH_FILES + 1}, (_, i) => ({path: i+'.txt', size: 0})), rejected()));
  await assert.rejects(importWorkspaceFiles(root, Array.from({length: 41}, (_, i) => ({path: i+'.txt', size: MAX_FILE_BYTES})), rejected()));
  await assert.rejects(importWorkspaceFiles(root, [{path:'large.txt',size:MAX_FILE_BYTES + 1}], rejected()));
  assert.equal(reviews, 0);
  const boundary = Array.from({length:40}, (_, i) => ({path:'limit/'+i+'.txt',size:MAX_FILE_BYTES}));
  assert.equal(boundary.reduce((s,f)=>s+f.size,0), MAX_BATCH_BYTES);
  assert.equal((await importWorkspaceFiles(root, boundary, { ...options, review: async () => false })).length, 40);
  assert.equal((await importWorkspaceFiles(root, Array.from({length:50},(_,i)=>({path:'empty/'+i,size:0})), {...options,review:async()=>false})).length, 50);
  pass('50 files/10 MiB exact boundaries, over-limit and per-file rejection before review');
  assert.equal((await run(['mismatch.txt'], { request: async () => 'wrong size' }))[0].status, 'failed');
  await assert.rejects(fs.stat(path.join(root, 'mismatch.txt')));
  pass('response must match reviewed size');
  const outside = await fs.mkdtemp(path.join(os.tmpdir(),'codemesh-batch-out-'));
  await fs.symlink(outside, path.join(root,'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  assert.equal((await run(['linked/escape.txt']))[0].status, 'failed');
  assert.deepEqual(await fs.readdir(outside), []);
  pass('junction destination rejected without outside writes');
  await fs.writeFile(path.join(root,'.gitignore'), 'ignored/\n');
  assert.equal((await run(['ignored/a.txt']))[0].status, 'failed');
  await fs.mkdir(path.join(root,'rules'));
  await fs.writeFile(path.join(root,'rules/.gitignore'),'*.txt\n');
  assert.equal((await run(['rules/a.txt']))[0].status, 'failed');
  await fs.writeFile(path.join(root,'existing.txt'),'keep');
  assert.equal((await run(['existing.txt'], { confirm: async () => { await fs.appendFile(path.join(root,'.gitignore'),'existing.txt\n'); return true; } }))[0].status,'failed');
  assert.equal(await fs.readFile(path.join(root,'existing.txt'),'utf8'),'keep');
  pass('root/nested ignore rules and rules changed during confirmation block writes');
  console.log(`Batch import: ${groups} focused groups passed`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
